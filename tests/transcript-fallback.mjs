import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = fs.readFileSync(path.join(here, '..', 'youtube', 'content.js'), 'utf8');

let messageListener = null;
let ccActive = false;
const resources = [];

const ccButton = {
  getAttribute(name) {
    if (name === 'aria-pressed') return ccActive ? 'true' : 'false';
    return null;
  },
  classList: { contains(name) { return name === 'ytp-button-active' && ccActive; } },
  click() {
    ccActive = !ccActive;
    if (ccActive) {
      resources.push({
        name: 'https://www.youtube.com/api/timedtext?v=test123&lang=en&pot=TESTPOT&c=WEB&fmt=json3',
        startTime: Date.now()
      });
    }
  }
};

function makeTextarea() {
  let value = '';
  return {
    set innerHTML(v) { value = String(v ?? ''); },
    get value() { return value; }
  };
}

const document = {
  documentElement: { dataset: {} },
  head: { appendChild() {} },
  title: 'Test - YouTube',
  createElement(tag) {
    if (tag === 'textarea') return makeTextarea();
    return {
      async: false,
      addEventListener() {},
      remove() {},
      set src(v) { this._src = v; },
      get src() { return this._src; }
    };
  },
  querySelector(selector) {
    if (selector.includes('ytp-subtitles-button')) return ccButton;
    return null;
  },
  querySelectorAll() { return []; }
};

const windowObj = {
  addEventListener() {},
  removeEventListener() {},
  dispatchEvent() {},
  location: { href: 'https://www.youtube.com/watch?v=test123' }
};

const chrome = {
  runtime: {
    getURL(pathname) { return `chrome-extension://test/${pathname}`; },
    onMessage: { addListener(fn) { messageListener = fn; } }
  }
};

const performanceMock = {
  now: () => Date.now(),
  getEntriesByType(type) { return type === 'resource' ? resources : []; }
};

async function fetchMock(input) {
  const url = String(input);
  const hasPot = new URL(url).searchParams.get('pot') === 'TESTPOT';
  const fmt = new URL(url).searchParams.get('fmt') || '';
  if (hasPot && fmt === 'json3') {
    const body = JSON.stringify({
      events: [
        { tStartMs: 0, dDurationMs: 1200, segs: [{ utf8: 'Protected captions now load.' }] },
        { tStartMs: 2000, dDurationMs: 1200, segs: [{ utf8: 'poToken fallback passed.' }] }
      ]
    });
    return { ok: true, status: 200, async text() { return body; } };
  }
  return { ok: true, status: 200, async text() { return ''; } };
}

const context = vm.createContext({
  window: windowObj,
  document,
  chrome,
  performance: performanceMock,
  fetch: fetchMock,
  navigator: { language: 'en-US' },
  location: windowObj.location,
  URL,
  CustomEvent: class CustomEvent { constructor(type, init) { this.type = type; this.detail = init?.detail; } },
  DOMParser: class DOMParser {},
  setTimeout,
  clearTimeout,
  console,
  Math,
  Date,
  RegExp,
  Object,
  Array,
  String,
  Number,
  Boolean,
  JSON,
  encodeURIComponent
});

vm.runInContext(source, context, { filename: 'youtube/content.js' });
if (typeof messageListener !== 'function') throw new Error('Content script did not register its message listener.');

const track = {
  languageCode: 'en',
  name: 'English',
  isAutoGenerated: true,
  baseUrl: 'https://www.youtube.com/api/timedtext?v=test123&lang=en&vssId=a.en'
};

const result = await new Promise((resolve, reject) => {
  const timeout = setTimeout(() => reject(new Error('Transcript test timed out.')), 5000);
  messageListener({ type: 'YT2GPT_GET_TRANSCRIPT', track }, {}, (response) => {
    clearTimeout(timeout);
    resolve(response);
  });
});

if (!result?.ok) throw new Error(`Expected successful fallback, got: ${JSON.stringify(result)}`);
if (!result.data?.text?.includes('poToken fallback passed.')) {
  throw new Error(`Expected protected caption text, got: ${result.data?.text || '<empty>'}`);
}
if (ccActive !== false) throw new Error('CC state was not restored after poToken harvesting.');

console.log('PASS: empty direct caption responses recovered via local poToken fallback.');
